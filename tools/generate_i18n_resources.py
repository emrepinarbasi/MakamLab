def _augment_report_fallbacks_from_source() -> None:
    """Keep report bundles in lockstep with the exporter without online lookup.

    The exporter always supplies an English fallback as the second argument of
    t(...).  Reading those literals here prevents a newly introduced chart,
    prose or table key from silently disappearing from non-English bundles.
    Generated property files still contain concrete strings; the application
    never parses Java source at runtime.
    """
    pattern = re.compile(r'(?<![A-Za-z0-9_])t\(\s*"([^"]+)"\s*,\s*"((?:\\.|[^"\\])*)"', re.DOTALL)
    sources = [
        ROOT / "src/main/java/com/makambox/studio/report/docx/SpecializedAnalysisDocxExporter.java",
        ROOT / "src/main/java/com/makambox/studio/report/docx/DocxStudyReportExporter.java",
        ROOT / "src/main/java/com/makambox/studio/report/docx/AcademicStudyCharts.java",
        ROOT / "src/main/java/com/makambox/studio/ui/MakamDocxReportHandler.java",
    ]
    for source in sources:
        if not source.is_file():
            continue
        text = source.read_text(encoding="utf-8")
        for key, encoded in pattern.findall(text):
            try:
                english = json.loads('"' + encoded + '"')
            except json.JSONDecodeError:
                english = encoded.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')
            BASE.setdefault(key, english)


_augment_report_fallbacks_from_source()


# Full translations are kept in a long-form UTF-8 TSV so linguists can review
# one locale or one key without editing Python.  A missing entry intentionally
# falls back to BASE, keeping every bundle complete and testable.
OVERRIDES: dict[str, dict[str, str]] = {}
TRANSLATIONS = ROOT / "tools" / "i18n-translations.tsv"
if TRANSLATIONS.is_file():
    with TRANSLATIONS.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            locale = row.get("locale", "").strip()
            key = row.get("key", "").strip()
            if locale and key in BASE:
                OVERRIDES.setdefault(locale, {})[key] = row.get("value", "")


def resource_suffix(tag: str) -> str:
    return tag.replace("-", "_")


def escape_property(value: str) -> str:
    return (value.replace("\\", "\\\\")
                 .replace("\n", "\\n")
                 .replace("\r", "\\r"))


def write_properties(path: Path, values: dict[str, str], tag: str) -> None:
    direction = next(row[4] for row in LANGUAGES if row[0] == tag)
    lines = [
        "# UTF-8; generated by tools/generate_i18n_resources.py",
        f"# Locale: {tag}; direction: {direction}",
        "# Makam/perde proper names are dynamic literals and must never be translated.",
    ]
    for key in sorted(values):
        lines.append(f"{key}={escape_property(values[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    write_properties(OUT / "messages.properties", BASE, "en-US")
    for row in LANGUAGES:
        tag = row[0]
        values = dict(BASE)
        values.update(OVERRIDES.get(tag, {}))
        write_properties(OUT / f"messages_{resource_suffix(tag)}.properties", values, tag)

    with (OUT / "languages.tsv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(("tag", "language", "script", "region", "direction",
                         "flag_region", "flag_emoji", "native_name",
                         "english_name", "turkish_name", "translation_tier"))
        for row in LANGUAGES:
            translated = set(OVERRIDES.get(row[0], {}))
            tier = "full" if set(BASE).issubset(translated) else ("core" if translated else "fallback")
            writer.writerow((*row, tier))

    print(f"Generated {len(LANGUAGES) + 1} bundles with {len(BASE)} keys in {OUT}")


if __name__ == "__main__":
    main()
